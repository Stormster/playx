// Local-only fixture: all control sockets are replaced, including inside iframes.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.PLAYX_WEB_URL || 'http://127.0.0.1:8789';
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.PLAYX_BROWSER_EXECUTABLE});
  try {
    for (const width of [480, 320]) {
      const context = await browser.newContext({viewport:{width,height:480}});
      await context.addInitScript(() => {
        window.TestKeyboard = {sent:[], unlimited:false, control(m) {if(m.t==='holdsetting')this.unlimited=m.anarchyHoldUnlimited;this.socket.onmessage({data:JSON.stringify(m)});}, state(mode='democracy') {this.control({t:'state',mode,anarchyHoldUnlimited:this.unlimited,viewers:1,tally:{},windowMs:1500,left:1000,played:0,paused:false,idle:false});}};
        window.WebSocket = class {
          constructor() {this.readyState=1; TestKeyboard.socket=this; setTimeout(()=>{this.onopen?.(); TestKeyboard.control({t:'hello',audioRate:16384,video:'chunks',steps:false,anarchyHoldUnlimited:TestKeyboard.unlimited}); TestKeyboard.state();},0);}
          send(data) {TestKeyboard.sent.push(JSON.parse(data));}
          close() {}
        };
      });
      // Block any network beyond the disposable local web fixture.
      await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
      const page = await context.newPage();
      for (const embedded of [false, true]) {
        if (embedded) {
          await page.goto(base + '/index.html');
          await page.evaluate(() => {document.body.innerHTML='<iframe title="PlayX fixture" src="/embed.html" style="position:fixed;inset:0;border:0;width:100%;height:100%"></iframe>';});
        } else await page.goto(base + '/index.html');
        const frame = embedded ? await (await page.locator('iframe').elementHandle()).contentFrame() : page;
        await frame.waitForFunction(()=>document.querySelector('[data-el="watchers"]').textContent==='1 playing');
        const votes = () => frame.evaluate(()=>TestKeyboard.sent.filter(m=>m.t==='vote'));
        const reset = () => frame.evaluate(()=>{TestKeyboard.sent=[];});
        const canvas = frame.locator('canvas');
        await canvas.click();
        assert(await canvas.evaluate(el=>document.activeElement===el),'click focuses game in its own frame');
        assert.equal(await frame.locator('.glass').evaluate(el=>getComputedStyle(el).outlineStyle),'solid');
        await reset();
        for (const [key,btn] of [['ArrowUp','up'],['ArrowDown','down'],['ArrowLeft','left'],['ArrowRight','right'],['w','up'],['s','down'],['a','left'],['d','right'],['W','up'],['z','a'],['j','a'],['x','b'],['k','b'],['Enter','start'],['Shift','select'],['q','l'],['e','r']]) {
          await page.keyboard.press(key);
          assert.deepEqual((await votes()).at(-1),{t:'vote',b:btn,n:1},key);
        }
        assert.equal((await votes()).length,17,'one vote per quick press');
        await reset();
        await page.keyboard.down('ArrowUp');
        await page.waitForTimeout(650);
        await page.keyboard.up('ArrowUp');
        const democracy = await votes();
        assert(democracy.length>=3 && democracy.length<=5,'held democracy renewals');
        assert(democracy.every(m=>m.b==='up' && Object.keys(m).sort().join(',')==='b,n,t'),'same single-voter wire shape');
        await page.waitForTimeout(250);
        assert.deepEqual(await votes(),democracy,'release stops hold');
        await reset();
        await page.keyboard.down('z');
        await page.waitForTimeout(3250);
        const longDemocracy=(await votes()).length;
        await page.waitForTimeout(350);
        assert((await votes()).length>longDemocracy,'Democracy renewal continues beyond Anarchy burst limit');
        await page.keyboard.up('z');
        await frame.evaluate(()=>TestKeyboard.state('anarchy'));
        await reset();
        await page.keyboard.down('w');
        await page.keyboard.down('ArrowUp');
        await page.waitForTimeout(650);
        assert((await votes()).length>=3 && (await votes()).length<=5,'aliases use one anarchy repeat stream');
        await page.keyboard.up('w');
        const aliasCount=(await votes()).length;
        await page.waitForTimeout(250);
        assert((await votes()).length>aliasCount,'remaining alias continues');
        await page.keyboard.up('ArrowUp');
        await reset();
        await page.keyboard.down('d');
        await page.waitForTimeout(3250);
        const bounded = await votes();
        assert(bounded.length>=8 && bounded.length<=10,'bounded hold burst');
        await page.waitForTimeout(450);
        assert.deepEqual(await votes(),bounded,'bounded stop does not auto-resume');
        await frame.evaluate(()=>TestKeyboard.control({t:'holdsetting',anarchyHoldUnlimited:true}));
        await page.keyboard.up('d');
        await page.keyboard.down('d');
        assert.equal((await votes()).length,bounded.length+1,'enabling unlimited clears local burst pause');
        assert.match(await frame.locator('[data-hold-help]').first().textContent(),/unlimited hold is on/);
        await page.waitForTimeout(3250);
        const unlimitedCount=(await votes()).length;
        await page.waitForTimeout(350);
        assert((await votes()).length>unlimitedCount,'unlimited Anarchy continues beyond 3 seconds');
        await frame.evaluate(()=>TestKeyboard.control({t:'holdsetting',anarchyHoldUnlimited:false}));
        const disabledCount=(await votes()).length;
        await page.waitForTimeout(350);
        assert.equal((await votes()).length,disabledCount,'turning unlimited off stops held input');
        await page.keyboard.up('d');
        await page.keyboard.press('d');
        assert.equal((await votes()).length,disabledCount,'turning off requires 2s quiet before fresh press');
        assert.match(await frame.locator('[data-hold-help]').first().textContent(),/up to 3 seconds/);
        await page.waitForTimeout(1800);
        await reset();
        await page.keyboard.down('ArrowLeft');
        const canceledCount=(await votes()).length;
        assert.equal(await canvas.evaluate(el=>!el.dispatchEvent(new KeyboardEvent('keydown',{key:'ArrowLeft',repeat:true,bubbles:true,cancelable:true}))),true,'OS repeats prevented');
        await frame.evaluate(()=>dispatchEvent(new Event('blur')));
        await page.waitForTimeout(250);
        assert.equal((await votes()).length,canceledCount,'blur cancels repeats');
        await page.keyboard.up('ArrowLeft');
        await canvas.click();
        await reset();
        await page.keyboard.down('a');
        await frame.evaluate(()=>TestKeyboard.state('democracy'));
        await page.waitForTimeout(250);
        assert.equal((await votes()).length,1,'mode transition stops hold');
        await page.keyboard.up('a');
        await reset();
        await page.keyboard.down('s');
        await frame.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));delete document.hidden;});
        await page.waitForTimeout(350);
        assert.equal((await votes()).length,1,'hidden document stops hold');
        await page.keyboard.up('s');
        await reset();
        await page.keyboard.press('Shift+Tab');
        assert.equal((await votes()).length,0,'Shift+Tab never votes Select');
        await frame.locator('[data-el="sound"]').focus();
        await page.keyboard.press('Enter');
        assert.equal(await frame.locator('[data-el="sound"]').getAttribute('aria-pressed'),'true');
        await frame.locator('[data-mode="anarchy"]').focus();
        await page.keyboard.press('Enter');
        assert.equal(await frame.locator('[data-mode="anarchy"]').getAttribute('aria-pressed'),'true');
        await frame.locator('[data-el="keyboardHelp"]').focus();
        await page.keyboard.press('Enter');
        assert(await frame.locator('#keyboard-guide').isVisible());
        assert.match(await frame.locator('#keyboard-guide').innerText(),/arrows or WASD/);
        assert(await frame.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'no horizontal overflow: '+JSON.stringify(await frame.evaluate(()=>[...document.querySelectorAll('*')].map(el=>{const r=el.getBoundingClientRect();return {tag:el.tagName,class:el.className,left:r.left,right:r.right,width:r.width};}).filter(r=>r.left<0||r.right>innerWidth))));
        if (embedded) assert(await frame.locator('.vbtn, .keyboard-toggle').evaluateAll(els=>els.every(el=>{const r=el.getBoundingClientRect();return r.left>=0 && r.right<=innerWidth && r.bottom<=innerHeight;})),'embed game controls remain in viewport');
        assert.equal((await votes()).length,0,'native controls do not vote');
        await frame.locator('[data-el="keyboardClose"]').click();
        assert(await frame.locator('#keyboard-guide').isHidden());
        await frame.evaluate(()=>{const input=document.createElement('input'); input.id='typing';document.querySelector('.xp-foot').append(input);const edit=document.createElement('div');edit.id='editing';edit.contentEditable='true';document.querySelector('.xp-foot').append(edit);});
        for (const selector of ['#typing','#editing']) {
          await frame.locator(selector).focus();
          await page.keyboard.type('wasdzxjqek');
          await page.keyboard.press('ArrowLeft');
          await page.keyboard.press('Shift');
        }
        assert.equal((await votes()).length,0,'editable fields retain normal keyboard usage');
        await canvas.click();
        for (const key of ['Control+w','Meta+z','Alt+ArrowLeft']) {
          await canvas.evaluate((el,key)=>{const [modifier,mapped]=key.split('+');const event=new KeyboardEvent('keydown',{key:mapped,ctrlKey:modifier==='Control',metaKey:modifier==='Meta',altKey:modifier==='Alt',bubbles:true,cancelable:true}); el.dispatchEvent(event); if(event.defaultPrevented) throw new Error('shortcut hijacked');},key);
        }
        assert.equal((await votes()).length,0,'browser shortcuts not hijacked');
        await frame.locator('[data-btn="a"]').click();
        assert.equal((await votes()).length,1,'pointer does not double-vote');
        await frame.locator('[data-btn="a"]').focus();
        await page.keyboard.press('Enter');
        await page.keyboard.press('Space');
        assert.equal((await votes()).length,3,'native game button keyboard activation');
        await canvas.click();
        await frame.evaluate(()=>TestKeyboard.control({t:'steps',on:true}));
        await page.keyboard.press('3');
        await page.keyboard.press('ArrowDown');
        assert.deepEqual((await votes()).at(-1),{t:'vote',b:'down',n:3});
        await frame.evaluate(()=>TestKeyboard.control({t:'steps',on:false}));
        await page.keyboard.press('5');
        await page.keyboard.press('ArrowDown');
        assert.deepEqual((await votes()).at(-1),{t:'vote',b:'down',n:1});
        await reset();
        await page.keyboard.down('q');
        await frame.evaluate(()=>TestKeyboard.control({t:'inputlimit',pauseMs:2000}));
        await page.waitForTimeout(350);
        assert.equal((await votes()).length,1,'server input pause stops repeats');
        await page.keyboard.up('q');
        await frame.evaluate(()=>TestKeyboard.control({t:'holdsetting',anarchyHoldUnlimited:true}));
        await page.keyboard.press('q');
        await page.keyboard.press('Shift');
        assert.equal((await votes()).length,1,'server pause also blocks new keyboard input');
        await page.waitForTimeout(1800);
        await reset();
        await page.keyboard.down('e');
        await frame.evaluate(()=>{TestKeyboard.socket.readyState=3;TestKeyboard.socket.onclose();});
        await page.waitForTimeout(800);
        assert.equal((await votes()).length,1,'disconnect cancels hold');
        await page.keyboard.up('e');
        assert.match(await frame.locator('[data-hold-help]').first().textContent(),/unlimited hold is on/,'reconnect hello/state restores unlimited flag');
        await frame.evaluate(()=>{TestKeyboard.unlimited=false;TestKeyboard.state();});
        assert.match(await frame.locator('[data-hold-help]').first().textContent(),/up to 3 seconds/,'state restores bounded flag');
        console.log(`PASS ${width}px ${embedded?'iframe':'page'}: mappings, focused play, bounded holds, cancellation, native controls, editable fields, shortcuts, steps, no overflow`);
      }
      await context.close();
    }
    const admin = await browser.newContext();
    await admin.addInitScript(()=>localStorage.setItem('xp-admin-token','local-fixture-token'));
    const adminPage = await admin.newPage();
    let settings = {theme:'flame',speed:1,paused:false,guard:true,steps:false,window:1500,modeLock:30,idle:60,emptyRoom:30,anarchyHoldUnlimited:false,simulatedMin:0,simulatedMax:0,simulatedPlayers:0};
    let failSimulation=false;
    const patches=[];
    await adminPage.route('**/*', async route => {
      const url=new URL(route.request().url());
      if(url.origin!==new URL(base).origin) return route.abort();
      if(url.pathname==='/admin-fixture') return route.fulfill({contentType:'text/html',body:fs.readFileSync(path.join(__dirname,'../server/admin.html'),'utf8')});
      if(url.pathname==='/admin/api/config') {const patch=route.request().postDataJSON();patches.push(patch);if(failSimulation&&'simulatedMin' in patch){failSimulation=false;return route.fulfill({status:500,body:'fixture failure'});}settings={...settings,...patch};if('simulatedMin' in patch)settings.simulatedPlayers=Math.max(patch.simulatedMin,Math.min(patch.simulatedMax,4));return route.fulfill({json:settings});}
      if(url.pathname==='/admin/api/status') return route.fulfill({json:{settings,viewers:1,played:0,inputs:0,mode:'anarchy',modeLockLeft:0,guardUndos:0,relay:null,gameAlive:true,quiet:false,idle:false,persistence:{degraded:false,lastSaved:null},started:new Date().toISOString()}});
      if(url.pathname==='/admin/api/saves') return route.fulfill({json:[]});
      return route.abort();
    });
    await adminPage.goto(base+'/admin-fixture');
    const unlimitedSwitch=adminPage.getByRole('switch',{name:'Unlimited Anarchy hold'});
    await unlimitedSwitch.waitFor({state:'visible'});
    assert.equal(await unlimitedSwitch.getAttribute('aria-checked'),'false');
    assert.match(await adminPage.locator('.row').filter({has:unlimitedSwitch}).innerText(),/Applies to everyone in this run/);
    await unlimitedSwitch.click();
    await adminPage.waitForFunction(()=>document.getElementById('anarchyHoldUnlimited').getAttribute('aria-checked')==='true');
    await unlimitedSwitch.focus();
    await adminPage.keyboard.press('Space');
    await adminPage.waitForFunction(()=>document.getElementById('anarchyHoldUnlimited').getAttribute('aria-checked')==='false');
    assert.deepEqual(patches,[{anarchyHoldUnlimited:true},{anarchyHoldUnlimited:false}]);
    const simMin=adminPage.getByRole('spinbutton',{name:'Simulated players minimum',exact:true});
    const simMax=adminPage.getByRole('spinbutton',{name:'Simulated players maximum',exact:true});
    const applied=(min,max)=>adminPage.waitForFunction(([a,b])=>document.getElementById('simulatedApply').disabled===false&&document.getElementById('simulatedMin').value===a&&document.getElementById('simulatedMax').value===b,[String(min),String(max)]);
    assert.equal(await simMin.inputValue(),'0');
    assert.equal(await simMax.inputValue(),'0');
    await adminPage.getByRole('button',{name:'+5',exact:true}).click();
    assert.deepEqual([await simMin.inputValue(),await simMax.inputValue()],['5','5'],'+5 keeps a fixed count fixed');
    await simMin.fill('3');
    await simMax.fill('7');
    await adminPage.waitForTimeout(2200);
    assert.equal(await simMin.inputValue(),'3','polling does not replace the min draft');
    assert.equal(await simMax.inputValue(),'7','polling does not replace the max draft');
    await adminPage.getByRole('button',{name:'+5',exact:true}).click();
    assert.equal(await simMax.inputValue(),'12');
    assert.equal(await simMin.inputValue(),'3','+5 grows only the ceiling of a range');
    await adminPage.getByRole('button',{name:'Apply',exact:true}).click();
    await applied(3,12);
    assert.deepEqual(patches.at(-1),{simulatedMin:3,simulatedMax:12});
    assert.match(await adminPage.locator('#simulatedRate').innerText(),/max 2\/sec/);
    const beforeInvalid=patches.length;
    await simMax.fill('51');
    await adminPage.getByRole('button',{name:'Apply',exact:true}).click();
    assert.equal(patches.length,beforeInvalid,'out-of-range draft never posts');
    await simMin.fill('9');
    await simMax.fill('4');
    await adminPage.getByRole('button',{name:'Apply',exact:true}).click();
    assert.equal(patches.length,beforeInvalid,'min above max never posts');
    await adminPage.getByRole('button',{name:'Off',exact:true}).click();
    await applied(0,0);
    assert.deepEqual(patches.at(-1),{simulatedMin:0,simulatedMax:0});
    failSimulation=true;
    await simMin.fill('2');
    await simMax.fill('5');
    await adminPage.getByRole('button',{name:'Apply',exact:true}).click();
    await adminPage.waitForFunction(()=>document.getElementById('toast').textContent==='Could not save simulated players. Try again.');
    assert.equal(await simMin.inputValue(),'2','failed save preserves the min draft');
    assert.equal(await simMax.inputValue(),'5','failed save preserves the max draft');
    assert.match(await adminPage.locator('#simulatedRate').innerText(),/^Preview:/);
    await adminPage.getByRole('button',{name:'Apply',exact:true}).click();
    await adminPage.waitForFunction(()=>document.getElementById('simulatedApply').disabled===false&&!document.getElementById('simulatedRate').textContent.startsWith('Preview:'));
    assert.deepEqual([settings.simulatedMin,settings.simulatedMax],[2,5],'retry saves the chosen range');
    await adminPage.reload();
    await simMin.waitFor({state:'visible'});
    assert.equal(await simMin.inputValue(),'2','saved min is restored after reload');
    assert.equal(await simMax.inputValue(),'5','saved max is restored after reload');
    assert.match(await adminPage.locator('#simulatedTotal').innerText(),/Public total: 5 \(1 viewers \+ 4 bots\)/,'public total uses the live count');
    await admin.close();
    console.log('PASS local admin: unlimited switch, simulated-range draft/polling/apply/off/validation/failure/retry/reload, exact config patches');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
